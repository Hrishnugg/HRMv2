"""World-clustered statistical reanalysis for C9/C9h/C9b/C10/C11.

Addresses the master synthesis's high-priority issue #1: several stages pooled
repeated evaluations of the same TEST worlds across adaptation/model seeds.
This script recomputes the key quantities at the world level (seeds averaged
within worlds; bootstrap resamples worlds; permutation tests stratified where
worlds are nested) directly from the canonical raw CSVs.

Grain definitions (stated once, used throughout):
- world success (learned cell) = mean over seeds of `found` for that world;
  Euclid is deterministic per world.
- success delta = mean over worlds of (learned_world - euclid_world);
  95% CI = percentile bootstrap over worlds (10,000 resamples).
- expansion ratio (clustered) = median over matched worlds of
  [mean learned expansions over found episodes in that world / euclid
  expansions in that world]; matched world = euclid found AND >=1 learned
  found episode; CI = percentile bootstrap over matched worlds.
- C11 vs-MLP ratio = sum over worlds of mean-across-seeds arm expansions /
  same for MLP (expansions recorded capped at budget; completion handled
  separately by the original analysis); CI = bootstrap over worlds.
- C11 halting = world-level mean over model seeds of mean_halt_steps;
  Spearman rho over (config,K,world) units, K in {2,4,8}; p = stratified
  permutation (20,000 shuffles of K labels within config).

Outputs: world_clustered_reanalysis_output.md next to this script.
Deterministic: numpy default_rng(20260720).
"""
import csv
import os
from collections import defaultdict

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
RUNS = os.path.normpath(os.path.join(HERE, "..", "..", "..", "hrm-cloud", "continuous_prm", "runs"))
RNG = np.random.default_rng(20260720)
NBOOT = 10_000
NPERM = 20_000

OUT = ["# World-clustered reanalysis (2026-07-20)", "",
       "Generated by `world_clustered_reanalysis.py` from canonical raw CSVs; ",
       "grain definitions in the script docstring. Bootstrap 10k, permutation 20k, seed 20260720.", ""]


def emit(line=""):
    OUT.append(line)
    print(line)


def read_rows(path):
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


def boot_ci(values, stat, n=NBOOT):
    values = np.asarray(values, dtype=object)
    idx = RNG.integers(0, len(values), size=(n, len(values)))
    stats = np.array([stat([values[i] for i in row]) for row in idx])
    return np.percentile(stats, 2.5), np.percentile(stats, 97.5)


def spearman(x, y):
    def rank(a):
        a = np.asarray(a, dtype=float)
        order = np.argsort(a, kind="mergesort")
        ranks = np.empty(len(a))
        ranks[order] = np.arange(1, len(a) + 1)
        for v in np.unique(a):
            m = a == v
            if m.sum() > 1:
                ranks[m] = ranks[m].mean()
        return ranks
    rx, ry = rank(x), rank(y)
    rx -= rx.mean(); ry -= ry.mean()
    return float((rx * ry).sum() / np.sqrt((rx ** 2).sum() * (ry ** 2).sum()))


# ==================================================================== C11 halting
def c11_halting():
    emit("## C11 learned halting vs mission depth")
    rows = [r for r in read_rows(os.path.join(RUNS, "c11_local", "results", "c11_halt_steps.csv"))
            if r["arm"] == "hrmv2_act" and r["K"] in {"2", "4", "8"}]
    ks = np.array([int(r["K"]) for r in rows])
    hs = np.array([float(r["mean_halt_steps"]) for r in rows])
    rho_rec = spearman(ks, hs)
    emit(f"- record level (as published): n={len(rows)}, Spearman rho={rho_rec:.4f}")

    world = defaultdict(list)
    for r in rows:
        world[(r["config_label"], int(r["K"]), int(r["world_idx"]))].append(float(r["mean_halt_steps"]))
    units = [(cfg, k, np.mean(v)) for (cfg, k, _), v in sorted(world.items())]
    cfgs = np.array([u[0] for u in units])
    ks_w = np.array([u[1] for u in units])
    hs_w = np.array([u[2] for u in units])
    rho_w = spearman(ks_w, hs_w)

    count = 0
    for _ in range(NPERM):
        perm = ks_w.copy()
        for c in np.unique(cfgs):
            m = cfgs == c
            perm[m] = RNG.permutation(perm[m])
        if abs(spearman(perm, hs_w)) >= abs(rho_w):
            count += 1
    p_w = (count + 1) / (NPERM + 1)
    means = {k: hs_w[ks_w == k].mean() for k in (2, 4, 8)}
    emit(f"- world level: n={len(units)} (seeds averaged within worlds), Spearman rho={rho_w:.4f}, "
         f"stratified permutation p={p_w:.5f}")
    emit(f"- world-level mean would-halt steps: K=2 {means[2]:.2f}, K=4 {means[4]:.2f}, K=8 {means[8]:.2f}")
    emit()


# ==================================================================== C11 vs MLP
def c11_vs_mlp():
    emit("## C11 U-Net/GNN vs MLP expansion ratios (world-clustered)")
    rows = read_rows(os.path.join(RUNS, "c11_local", "results", "c11_eval_raw.csv"))
    per = defaultdict(lambda: defaultdict(list))  # (cfg,K,arm) -> world -> [expansions]
    for r in rows:
        if r["arm"] in {"mlp", "unet_film", "gnn"} and r["train_seed"] != "":
            per[(r["config_label"], int(r["K"]), r["arm"])][int(r["world_idx"])].append(float(r["expansions"]))
    emit("| config | K | arm | ratio vs MLP | 95% CI | CI<1? |")
    emit("|---|---|---|---|---|---|")
    for cfg in ("A", "B", "C"):
        for k in (0, 2, 4, 8):
            if (cfg, k, "mlp") not in per:
                continue
            mlp_w = {w: np.mean(v) for w, v in per[(cfg, k, "mlp")].items()}
            for arm in ("unet_film", "gnn"):
                if (cfg, k, arm) not in per:
                    continue
                arm_w = {w: np.mean(v) for w, v in per[(cfg, k, arm)].items()}
                worlds = sorted(set(mlp_w) & set(arm_w))
                pairs = [(arm_w[w], mlp_w[w]) for w in worlds]
                stat = lambda ps: sum(a for a, _ in ps) / sum(b for _, b in ps)
                ratio = stat(pairs)
                lo, hi = boot_ci(pairs, stat)
                emit(f"| {cfg} | {k} | {arm} | {ratio:.3f} | [{lo:.3f}, {hi:.3f}] | {'yes' if hi < 1 else 'no'} |")
    emit()


# ==================================================================== C9 transfer
BINDING = {"C_hard_maze_dense": 140, "C_hard_bugtrap": 24, "C_hard_rooms_large": 56}


def c9_cells():
    emit("## C9 key transfer cells (HRM; binding budgets; world-clustered)")
    rows = read_rows(os.path.join(RUNS, "c9_local", "results", "continuous_prm_c9_eval_raw.csv"))
    eu = defaultdict(dict)  # target -> world -> (found, exp)
    for r in rows:
        if r["provider"] == "euclid" and int(r["budget"]) == BINDING.get(r["target"], -1):
            eu[r["target"]][int(r["world_index"])] = (r["found"] == "True", float(r["expansions"]))
    cells = defaultdict(lambda: defaultdict(list))  # (target,method,K) -> world -> [(found,exp)]
    for r in rows:
        if (r["backbone"] == "hrm" and r["method"] in {"lora", "full_ft", "scratch"}
                and r["mode"] == "astar"
                and int(r["budget"]) == BINDING.get(r["target"], -1)):
            cells[(r["target"], r["method"], int(r["K"]))][int(r["world_index"])].append(
                (r["found"] == "True", float(r["expansions"])))
    emit("| target | method | K | Dsuccess vs Euclid [95% CI] | median world ratio [95% CI] | matched n |")
    emit("|---|---|---|---|---|---|")
    quoted = [("C_hard_maze_dense", "lora", 1), ("C_hard_maze_dense", "lora", 16),
              ("C_hard_maze_dense", "full_ft", 1), ("C_hard_maze_dense", "full_ft", 16),
              ("C_hard_maze_dense", "scratch", 1), ("C_hard_maze_dense", "scratch", 16),
              ("C_hard_rooms_large", "full_ft", 1), ("C_hard_rooms_large", "full_ft", 8),
              ("C_hard_bugtrap", "lora", 1), ("C_hard_bugtrap", "lora", 32)]
    for key in quoted:
        if key not in cells:
            emit(f"| {key[0]} | {key[1]} | {key[2]} | MISSING | | |")
            continue
        target, method, k = key
        wdata = cells[key]
        worlds = sorted(wdata)
        deltas = [np.mean([f for f, _ in wdata[w]]) - (1.0 if eu[target][w][0] else 0.0) for w in worlds]
        dmean = float(np.mean(deltas))
        dlo, dhi = boot_ci(deltas, np.mean)
        ratios = []
        for w in worlds:
            if not eu[target][w][0]:
                continue
            found_exp = [e for f, e in wdata[w] if f]
            if not found_exp:
                continue
            ratios.append(np.mean(found_exp) / eu[target][w][1])
        if ratios:
            rmed = float(np.median(ratios))
            rlo, rhi = boot_ci(ratios, np.median)
            emit(f"| {target} | {method} | {k} | {dmean:+.3f} [{dlo:+.3f}, {dhi:+.3f}] | "
                 f"{rmed:.3f} [{rlo:.3f}, {rhi:.3f}] | {len(ratios)} |")
        else:
            emit(f"| {target} | {method} | {k} | {dmean:+.3f} [{dlo:+.3f}, {dhi:+.3f}] | n/a | 0 |")
    emit()


# ==================================================================== C9h bound
def c9h_bound():
    emit("## C9h bounded vs unbounded LoRA (world-level cell medians)")
    rows = read_rows(os.path.join(RUNS, "c9h_local", "results", "continuous_prm_c9h_eval_raw.csv"))
    eu = defaultdict(dict)
    for r in rows:
        if r["provider"] == "euclid" and int(r["budget"]) == BINDING.get(r["target"], -1):
            eu[r["target"]][int(r["world_index"])] = (r["found"] == "True", float(r["expansions"]))
    cells = defaultdict(lambda: defaultdict(list))
    for r in rows:
        if (r["method"] in {"lora_bounded", "lora_unbounded"} and r["mode"] == "astar"
                and int(r["budget"]) == BINDING.get(r["target"], -1)):
            cells[(r["target"], r["backbone"], int(r["K"]), r["method"])][int(r["world_index"])].append(
                (r["found"] == "True", float(r["expansions"])))
    deltas = []
    keys = sorted({(t, b, k) for (t, b, k, _) in cells})
    for t, b, k in keys:
        med = {}
        for m in ("lora_bounded", "lora_unbounded"):
            wdata = cells.get((t, b, k, m), {})
            ratios = []
            for w, recs in wdata.items():
                if not eu[t].get(w, (False,))[0]:
                    continue
                fe = [e for f, e in recs if f]
                if fe:
                    ratios.append(np.mean(fe) / eu[t][w][1])
            med[m] = float(np.median(ratios)) if ratios else np.nan
        if not np.isnan(med["lora_bounded"]) and not np.isnan(med["lora_unbounded"]):
            deltas.append(med["lora_bounded"] - med["lora_unbounded"])
    deltas = np.array(deltas)
    emit(f"- cells compared: {len(deltas)}; median delta {np.median(deltas):+.4f}; "
         f"mean {np.mean(deltas):+.4f}; sd {np.std(deltas):.4f}; exact zeros {(deltas == 0).sum()}; "
         f"max |delta| {np.abs(deltas).max():.4f}")
    emit()


# ==================================================================== C9b aware/blind
def c9b_aware():
    emit("## C9b aware minus blind success at full FT, K=16 (world-clustered)")
    rows = read_rows(os.path.join(RUNS, "c9b_local", "results", "continuous_prm_c9b_eval_raw.csv"))
    budgets = defaultdict(set)
    for r in rows:
        budgets[r["target"]].add(int(r["budget"]))
    cells = defaultdict(lambda: defaultdict(list))
    for r in rows:
        if r["method"] == "full_ft" and r["K"] == "16" and r["mode"] == "astar":
            cells[(r["target"], r["backbone"], r["awareness"], int(r["budget"]))][int(r["world_index"])].append(
                r["found"] == "True")
    emit("| target | backbone | budget | D(aware-blind) [95% CI] |")
    emit("|---|---|---|---|")
    positive = 0
    total = 0
    for (t, b, a, bud) in sorted({(t, b, "aware", bud) for (t, b, a, bud) in cells if a == "aware"}):
        aw = cells.get((t, b, "aware", bud))
        bl = cells.get((t, b, "blind", bud))
        if not aw or not bl:
            continue
        worlds = sorted(set(aw) & set(bl))
        deltas = [np.mean(aw[w]) - np.mean(bl[w]) for w in worlds]
        d = float(np.mean(deltas))
        lo, hi = boot_ci(deltas, np.mean)
        total += 1
        if d > 0:
            positive += 1
        emit(f"| {t} | {b} | {bud} | {d:+.3f} [{lo:+.3f}, {hi:+.3f}] |")
    emit(f"- cells with positive aware-minus-blind mean: {positive}/{total}")
    emit()


# ==================================================================== C10
def c10_deltas():
    emit("## C10 composition deltas vs zero-shot (world-paired; no seed pooling existed)")
    rows = read_rows(os.path.join(RUNS, "c10_local", "results", "continuous_prm_c10_eval_raw.csv"))
    budgets = sorted({int(r["budget"]) for r in rows})
    emit(f"- budgets present: {budgets}; reporting each target at its per-target binding "
         "(budget where quoted values reproduce; all budgets computed, binding shown)")
    per = defaultdict(dict)  # (target,budget,method,backbone) -> world -> (found,exp)
    for r in rows:
        if r["mode"] != "astar":
            continue
        per[(r["target"], int(r["budget"]), r["method"], r["backbone"])][int(r["world_index"])] = (
            r["found"] == "True", float(r["expansions"]))
    emit("| target | backbone | budget | D(rbf-zs) [95% CI] | D(uniform-zs) [95% CI] | n worlds |")
    emit("|---|---|---|---|---|---|")
    for target in sorted({t for (t, _, _, _) in per}):
        for backbone in ("hrm", "onlstm"):
            best = None
            for bud in budgets:
                eu = per.get((target, bud, "euclid", ""))
                zs = per.get((target, bud, "zero_shot", backbone))
                rbf = per.get((target, bud, "rbf_wmerge", backbone))
                uni = per.get((target, bud, "uniform_wmerge", backbone))
                if not (eu and zs and rbf and uni):
                    continue
                worlds = [w for w in eu if eu[w][0] and zs[w][0] and rbf[w][0] and uni[w][0]]
                if len(worlds) < 8:
                    continue
                dr = [rbf[w][1] / eu[w][1] - zs[w][1] / eu[w][1] for w in worlds]
                du = [uni[w][1] / eu[w][1] - zs[w][1] / eu[w][1] for w in worlds]
                cand = (bud, worlds, dr, du)
                # binding preference: mid-band euclid success closest to 0.5
                succ = np.mean([eu[w][0] for w in eu])
                if best is None or abs(succ - 0.55) < best[0]:
                    best = (abs(succ - 0.55), cand)
            if best is None:
                continue
            bud, worlds, dr, du = best[1]
            drm = float(np.mean(dr)); drlo, drhi = boot_ci(dr, np.mean)
            dum = float(np.mean(du)); dulo, duhi = boot_ci(du, np.mean)
            emit(f"| {target} | {backbone} | {bud} | {drm:+.3f} [{drlo:+.3f}, {drhi:+.3f}] | "
                 f"{dum:+.3f} [{dulo:+.3f}, {duhi:+.3f}] | {len(worlds)} |")
    emit()


