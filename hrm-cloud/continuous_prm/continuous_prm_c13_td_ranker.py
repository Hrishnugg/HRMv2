def main() -> None:
    cfg = config_from_args(parse_args())
    out_dir = Path(cfg.out_dir)
    train_path = out_dir / "datasets" / "c13_td_train.npz"
    val_path = out_dir / "datasets" / "c13_td_val.npz"
    model_names = C13.parse_csv(cfg.models)
    device = resolve_device(cfg.device)
    C.set_global_seed(cfg.seed)

    if cfg.mode in {"collect", "full"}:
        train_path = collect_rollout_dataset(
            cfg,
            "train",
            C13.parse_csv(cfg.train_suites),
            cfg.train_worlds,
            seed_offset=0,
        )
        val_path = collect_rollout_dataset(
            cfg,
            "val",
            C13.parse_csv(cfg.train_suites),
            cfg.val_worlds,
            seed_offset=500_000,
        )
        print(f"train={train_path}\nval={val_path}")

    checkpoints: Dict[str, Path] = {}
    if cfg.mode in {"train", "full"}:
        if not train_path.exists() or not val_path.exists():
            raise FileNotFoundError("collect train/validation datasets before training")
        for model_name in model_names:
            checkpoints[model_name] = train_ranker(cfg, model_name, train_path, val_path, device)
            print(f"checkpoint[{model_name}]={checkpoints[model_name]}")
    else:
        checkpoints = {
            model_name: out_dir / "checkpoints" / f"c13_td_{model_name}.pt"
            for model_name in model_names
        }

    if cfg.mode in {"eval", "full"}:
        missing = [str(path) for path in checkpoints.values() if not path.exists()]
        if missing:
            raise FileNotFoundError(f"missing checkpoints: {missing}")
        outputs = evaluate_rankers(cfg, checkpoints, device)
        for key, value in outputs.items():
            print(f"{key}={value}")

    C13.write_json(
        out_dir / "c13_td_manifest.json",
        {
            "experiment": "C13-B",
            "config": asdict(cfg),
            "target_source": TARGET_SOURCE,
            "target_aggregation": TARGET_AGGREGATION,
            "target_transform": TARGET_TRANSFORM,
            "shortest_path_target": SHORTEST_PATH_TARGET,
            "oracle_policy_access": ORACLE_POLICY_ACCESS,
            "status": "completed_requested_mode",
        },
    )


if __name__ == "__main__":
    main()
