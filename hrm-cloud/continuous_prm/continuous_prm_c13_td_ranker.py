def collect_rollout_dataset(
    cfg: C13TDConfig,
    split: str,
    suites: Sequence[str],
    worlds_per_suite: int,
    seed_offset: int,
) -> Path:
    M7.install_c7_hard_maps()
    specs = C.build_anchor_specs()
    state_cfg = cfg.state_cfg()
    policy_cfg = cfg.policy_cfg()
    xs: List[np.ndarray] = []
    ys: List[np.ndarray] = []
    raw_ys: List[np.ndarray] = []
    counts_all: List[np.ndarray] = []
    world_ids: List[np.ndarray] = []
    records: List[Dict[str, Any]] = []
    global_world_id = 0

    for suite_idx, suite in enumerate(suites):
        if suite not in specs:
            raise KeyError(f"unknown suite {suite!r}; have {sorted(specs)}")
        accepted = 0
        candidate_worlds = int(worlds_per_suite) * int(cfg.max_world_retries)
        for _, world, world_seed in C13.iter_worlds(
            specs[suite],
            suite_idx,
            candidate_worlds,
            int(cfg.seed) + int(seed_offset),
            retry=cfg.max_world_retries,
        ):
            rm = C.build_prm(
                world,
                C.RoadmapConfig(n_nodes=int(cfg.train_nodes), k_neighbors=int(cfg.roadmap_k)),
                seed=world_seed + 17,
            )
            if rm is None:
                continue
            rollout_seed = world_seed + 71_003 + int(seed_offset)
            indices, returns, counts, rollout_stats = collect_rollout_targets_from_roadmap(
                rm,
                world.side_len,
                random.Random(rollout_seed),
                policy_cfg,
            )
            if len(indices) < int(cfg.min_labeled_nodes):
                continue
            all_features = C13.make_local_state_features(world, rm.points, rm.adj, state_cfg)
            target, raw_target = rollout_residual_targets(
                rm.points,
                indices,
                returns,
                world.side_len,
                policy_cfg.max_norm_residual,
            )
            xs.append(all_features[indices])
            ys.append(target)
            raw_ys.append(raw_target)
            counts_all.append(counts)
            world_ids.append(np.full(len(indices), global_world_id, dtype=np.int32))
            records.append(
                {
                    "world_id": global_world_id,
                    "suite": suite,
                    "suite_world_index": accepted,
                    "world_seed": world_seed,
                    "roadmap_seed": world_seed + 17,
                    "rollout_seed": rollout_seed,
                    "nodes": len(rm.points),
                    "edges": sum(len(a) for a in rm.adj) // 2,
                    "samples": len(indices),
                    "coverage_rate": len(indices) / max(1, len(rm.points)),
                    "target_mean": float(np.mean(target)),
                    "target_clip_rate": float(
                        np.mean(np.log1p(raw_target) > policy_cfg.max_norm_residual)
                    ),
                    **rollout_stats,
                }
            )
            global_world_id += 1
            accepted += 1
            if accepted >= int(worlds_per_suite):
                break
        if accepted < int(worlds_per_suite):
            raise RuntimeError(f"{split}/{suite} under-filled: {accepted}/{worlds_per_suite}")

    if not xs:
        raise RuntimeError(f"no C13-B samples collected for split {split!r}")
    dataset_dir = C13.ensure_dir(Path(cfg.out_dir) / "datasets")
    path = dataset_dir / f"c13_td_{split}.npz"
    np.savez_compressed(
        path,
        x=np.concatenate(xs).astype(np.float32),
        y=np.concatenate(ys).astype(np.float32),
        raw_y=np.concatenate(raw_ys).astype(np.float32),
        rollout_count=np.concatenate(counts_all).astype(np.int32),
        world_id=np.concatenate(world_ids).astype(np.int32),
    )
    metadata = {
        "experiment": "C13-B",
        "split": split,
        "target_source": TARGET_SOURCE,
        "target_aggregation": TARGET_AGGREGATION,
        "target_transform": TARGET_TRANSFORM,
        "max_log_residual": float(cfg.max_norm_residual),
        "shortest_path_target": SHORTEST_PATH_TARGET,
        "oracle_policy_access": ORACLE_POLICY_ACCESS,
        "shortest_path_result_used_as_input": False,
        "dijkstra_role": "roadmap_connectivity_filter_and_evaluation_only",
        "behavior_policy_scope": "current_one_hop_actions_goal_geometry_visit_history",
        "label_history_condition": "fresh_start_zero_visit_history_only",
        "runtime_model_scope": "current_geometry_bounded_rays_one_hop_actions",
        "forbidden_inputs": list(C13.FORBIDDEN_INPUTS),
        "state_config": asdict(state_cfg),
        "rollout_policy": asdict(policy_cfg),
        "roadmap_nodes": int(cfg.train_nodes),
        "roadmap_k": int(cfg.roadmap_k),
        "suites": list(suites),
        "worlds": records,
        "n_samples": int(sum(len(y) for y in ys)),
    }
    C13.write_json(path.with_suffix(".metadata.json"), metadata)
    return path


