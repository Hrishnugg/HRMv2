@dataclass(frozen=True)
class RolloutEpisode:
    nodes: Tuple[int, ...]
    edge_costs: Tuple[float, ...]
    found: bool

    @property
    def steps(self) -> int:
        return len(self.edge_costs)

    @property
    def total_cost(self) -> float:
        return float(sum(self.edge_costs))


def _weighted_choice(rng: random.Random, items: Sequence[int], weights: Sequence[float]) -> int:
    if len(items) != len(weights) or not items:
        raise ValueError("weighted choice requires equally sized non-empty inputs")
    total = float(sum(max(0.0, float(w)) for w in weights))
    if not math.isfinite(total) or total <= 0.0:
        return int(items[rng.randrange(len(items))])
    threshold = rng.random() * total
    running = 0.0
    for item, weight in zip(items, weights):
        running += max(0.0, float(weight))
        if running >= threshold:
            return int(item)
    return int(items[-1])


def local_behavior_rollout(
    points: np.ndarray,
    adj: Sequence[Sequence[Tuple[int, float]]],
    start_idx: int,
    side_len: float,
    rng: random.Random,
    cfg: RolloutPolicyConfig,
    goal_idx: int = 1,
) -> RolloutEpisode:
    """Execute a stochastic policy using only current one-hop information.

    Euclidean distance is evaluated for the currently visible actions.  The
    policy does not inspect adjacency lists belonging to nodes it has not yet
    visited and does not call any graph-search routine.
    """

    pts = np.asarray(points, dtype=np.float64)
    n = len(pts)
    if len(adj) != n:
        raise ValueError("points and adjacency size differ")
    if not (0 <= int(start_idx) < n and 0 <= int(goal_idx) < n):
        raise IndexError("start or goal index outside graph")
    if float(side_len) <= 0.0:
        raise ValueError("side_len must be positive")

    current = int(start_idx)
    nodes = [current]
    edge_costs: List[float] = []
    visits = np.zeros(n, dtype=np.int32)
    visits[current] = 1
    max_steps = max(1, int(cfg.max_steps_factor) * n)
    previous: Optional[int] = None
    goal = pts[int(goal_idx)]

    for _ in range(max_steps):
        if current == int(goal_idx):
            return RolloutEpisode(tuple(nodes), tuple(edge_costs), True)
        nbrs = [(int(v), float(w)) for v, w in adj[current] if float(w) >= 0.0]
        if not nbrs:
            break

        candidates = [v for v, _ in nbrs]
        if rng.random() < float(cfg.epsilon):
            # Exploration still disfavors repeatedly cycling through one node.
            weights = [1.0 / (1.0 + float(visits[v])) for v in candidates]
        else:
            scores: List[float] = []
            for v, edge_cost in nbrs:
                score = (
                    edge_cost / float(side_len)
                    + float(np.linalg.norm(pts[v] - goal)) / float(side_len)
                    + float(cfg.revisit_penalty_frac) * float(visits[v])
                )
                if previous is not None and v == previous and len(nbrs) > 1:
                    score += float(cfg.reverse_penalty_frac)
                scores.append(score)
            minimum = min(scores)
            temperature = max(1.0e-6, float(cfg.temperature))
            weights = [math.exp(-min(60.0, (score - minimum) / temperature)) for score in scores]

        chosen = _weighted_choice(rng, candidates, weights)
        edge_cost = next(w for v, w in nbrs if v == chosen)
        previous, current = current, chosen
        nodes.append(current)
        edge_costs.append(float(edge_cost))
        visits[current] += 1

    return RolloutEpisode(tuple(nodes), tuple(edge_costs), current == int(goal_idx))


def realized_returns(episode: RolloutEpisode) -> np.ndarray:
    """Return the undiscounted suffix cost at every visited state."""

    if len(episode.nodes) != len(episode.edge_costs) + 1:
        raise ValueError("episode must contain one more node than edge costs")
    returns = np.zeros(len(episode.nodes), dtype=np.float64)
    running = 0.0
    for idx in range(len(episode.edge_costs) - 1, -1, -1):
        running += float(episode.edge_costs[idx])
        returns[idx] = running
    return returns


def aggregate_all_visit_returns_for_audit(
    episodes: Iterable[RolloutEpisode],
) -> Tuple[Dict[int, float], Dict[int, int], Dict[str, Any]]:
    """Audit every visited-state return; this is not a training target."""

    values: DefaultDict[int, List[float]] = defaultdict(list)
    total = 0
    successes = 0
    steps: List[int] = []
    costs: List[float] = []
    for episode in episodes:
        total += 1
        if not episode.found:
            continue
        successes += 1
        returns = realized_returns(episode)
        for node, value in zip(episode.nodes, returns):
            values[int(node)].append(float(value))
        steps.append(episode.steps)
        costs.append(episode.total_cost)
    medians = {node: float(np.median(samples)) for node, samples in values.items()}
    counts = {node: len(samples) for node, samples in values.items()}
    stats = {
        "episodes": total,
        "successful_episodes": successes,
        "success_rate": successes / max(1, total),
        "labeled_nodes": len(medians),
        "successful_steps_mean": float(np.mean(steps)) if steps else float("nan"),
        "successful_cost_mean": float(np.mean(costs)) if costs else float("nan"),
        "aggregation": "median_all_visit_return_audit_only",
    }
    return medians, counts, stats

def aggregate_successful_start_returns(
    episodes_by_start: Mapping[int, Sequence[RolloutEpisode]],
) -> Tuple[Dict[int, float], Dict[int, int], Dict[str, Any]]:
    """Aggregate only fresh-start returns, so hidden visit history cannot alias labels."""

    medians: Dict[int, float] = {}
    counts: Dict[int, int] = {}
    total = 0
    successes = 0
    steps: List[int] = []
    costs: List[float] = []
    for start, episodes in episodes_by_start.items():
        successful_costs: List[float] = []
        for episode in episodes:
            total += 1
            if not episode.found:
                continue
            successes += 1
            successful_costs.append(episode.total_cost)
            steps.append(episode.steps)
            costs.append(episode.total_cost)
        if successful_costs:
            medians[int(start)] = float(np.median(successful_costs))
            counts[int(start)] = len(successful_costs)
    stats = {
        "episodes": total,
        "successful_episodes": successes,
        "success_rate": successes / max(1, total),
        "labeled_nodes": len(medians),
        "successful_steps_mean": float(np.mean(steps)) if steps else float("nan"),
        "successful_cost_mean": float(np.mean(costs)) if costs else float("nan"),
        "aggregation": TARGET_AGGREGATION,
        "history_condition": "visit_history_reset_at_each_labeled_start",
    }
    return medians, counts, stats



def collect_rollout_targets_from_roadmap(
    roadmap: Any,
    side_len: float,
    rng: random.Random,
    cfg: RolloutPolicyConfig,
    goal_idx: int = 1,
) -> Tuple[np.ndarray, np.ndarray, np.ndarray, Dict[str, Any]]:
    """Collect targets while deliberately reading only ``points`` and ``adj``.

    Accepting a roadmap-like object makes the no-oracle property testable: a
    sentinel ``dist_to_goal`` property can raise if this function ever touches
    it.
    """

    points = np.asarray(roadmap.points, dtype=np.float64)
    adj = roadmap.adj
    n = len(points)
    episodes_by_start: Dict[int, List[RolloutEpisode]] = {
        start: [
            local_behavior_rollout(points, adj, start, side_len, rng, cfg, goal_idx=goal_idx)
            for _ in range(max(1, int(cfg.rollouts_per_start)))
        ]
        for start in range(n)
    }
    returns_by_node, counts_by_node, stats = aggregate_successful_start_returns(episodes_by_start)
    node_indices = np.array(sorted(returns_by_node), dtype=np.int64)
    returns = np.array([returns_by_node[int(i)] for i in node_indices], dtype=np.float64)
    counts = np.array([counts_by_node[int(i)] for i in node_indices], dtype=np.int32)
    return node_indices, returns, counts, stats


def rollout_residual_targets(
    points: np.ndarray,
    node_indices: np.ndarray,
    realized_costs: np.ndarray,
    side_len: float,
    max_norm_residual: float,
    goal_idx: int = 1,
) -> Tuple[np.ndarray, np.ndarray]:
    pts = np.asarray(points, dtype=np.float64)
    indices = np.asarray(node_indices, dtype=np.int64)
    costs = np.asarray(realized_costs, dtype=np.float64)
    euclid = C13.euclidean_to_goal(pts, pts[int(goal_idx)])[indices]
    raw = np.maximum(0.0, costs - euclid) / max(C.EPS, float(side_len))
    transformed = np.log1p(raw)
    clipped = np.clip(transformed, 0.0, float(max_norm_residual))
    return clipped.astype(np.float32), raw.astype(np.float32)


