def _search_row(
    base: Mapping[str, Any],
    provider: str,
    mode: str,
    result: Mapping[str, Any],
    optimal: float,
    search_seconds: float,
    focal_w: Optional[float] = None,
    inference_seconds: float = 0.0,
) -> Dict[str, Any]:
    cost = float(result["cost"])
    return {
        **base,
        "provider": provider,
        "mode": mode,
        "focal_w": "" if focal_w is None else float(focal_w),
        "found": bool(result["found"]),
        "expansions": int(result["expansions"]),
        "closed": int(result["closed"]),
        "cost": cost if math.isfinite(cost) else "",
        "cost_ratio": cost / optimal if math.isfinite(cost) and optimal > C.EPS else "",
        "inference_seconds": float(inference_seconds),
        "search_seconds": float(search_seconds),
    }


def _run_astar(
    base: Mapping[str, Any],
    provider: str,
    adj: List[List[Tuple[int, float]]],
    heuristic: np.ndarray,
    budget: int,
    optimal: float,
    inference_seconds: float = 0.0,
) -> Dict[str, Any]:
    t0 = time.perf_counter()
    result = C.astar_search(adj, heuristic, int(budget))
    return _search_row(
        base,
        provider,
        "astar",
        result,
        optimal,
        time.perf_counter() - t0,
        inference_seconds=inference_seconds,
    )

def _run_focal(
    base: Mapping[str, Any],
    provider: str,
    adj: List[List[Tuple[int, float]]],
    euclid: np.ndarray,
    rank: np.ndarray,
    budget: int,
    optimal: float,
    focal_w: float,
    inference_seconds: float = 0.0,
) -> Dict[str, Any]:
    t0 = time.perf_counter()
    result = focal_astar_search(
        adj,
        euclid,
        rank,
        int(budget),
        w=float(focal_w),
    )
    return _search_row(
        base,
        provider,
        "focal",
        result,
        optimal,
        time.perf_counter() - t0,
        focal_w=float(focal_w),
        inference_seconds=inference_seconds,
    )



def summarize_evaluation(rows: Sequence[Dict[str, Any]]) -> List[Dict[str, Any]]:
    euclid_expansions: Dict[Tuple[Any, ...], float] = {}
    euclid_focal_expansions: Dict[Tuple[Any, ...], float] = {}
    for row in rows:
        if row.get("provider") == "euclid":
            key = (row["suite"], row["world_index"], row["requested_nodes"], row["budget"])
            euclid_expansions[key] = float(row["expansions"])
        if row.get("provider") == "euclid_focal_rank":
            key = (row["suite"], row["world_index"], row["requested_nodes"], row["budget"], float(row["focal_w"]))
            euclid_focal_expansions[key] = float(row["expansions"])

    grouped: DefaultDict[Tuple[Any, ...], List[Dict[str, Any]]] = defaultdict(list)
    for row in rows:
        if row.get("provider") == "build_failure":
            continue
        key = (
            row["provider"],
            row["mode"],
            row.get("focal_w", ""),
            row["requested_nodes"],
            row["budget"],
        )
        grouped[key].append(row)

    summary: List[Dict[str, Any]] = []
    for (provider, mode, focal_w, nodes, budget), group in sorted(grouped.items(), key=lambda item: str(item[0])):
        ratios = [float(r["cost_ratio"]) for r in group if r.get("cost_ratio") != ""]
        deltas: List[float] = []
        focal_deltas: List[float] = []
        for row in group:
            match = (row["suite"], row["world_index"], row["requested_nodes"], row["budget"])
            if match in euclid_expansions:
                deltas.append(float(row["expansions"]) - euclid_expansions[match])
            if mode == "focal":
                focal_match = (*match, float(row["focal_w"]))
                if focal_match in euclid_focal_expansions:
                    focal_deltas.append(float(row["expansions"]) - euclid_focal_expansions[focal_match])
        summary.append(
            {
                "provider": provider,
                "mode": mode,
                "focal_w": focal_w,
                "requested_nodes": nodes,
                "budget": budget,
                "worlds": len(group),
                "success_rate": float(np.mean([bool(r["found"]) for r in group])),
                "expansions_mean": float(np.mean([float(r["expansions"]) for r in group])),
                "expansion_delta_vs_euclid_mean": float(np.mean(deltas)) if deltas else "",
                "expansion_delta_vs_euclid_focal_mean": float(np.mean(focal_deltas)) if focal_deltas else "",
                "cost_ratio_mean_success": float(np.mean(ratios)) if ratios else "",
                "inference_seconds_mean": float(np.mean([float(r["inference_seconds"]) for r in group])),
                "search_seconds_mean": float(np.mean([float(r["search_seconds"]) for r in group])),
            }
        )
    return summary


def evaluate_rankers(
    cfg: C13TDConfig,
    checkpoints: Mapping[str, Path],
    device: torch.device,
) -> Dict[str, Path]:
    M7.install_c7_hard_maps()
    specs = C.build_anchor_specs()
    models = {name: load_ranker(cfg, name, path, device) for name, path in checkpoints.items()}
    densities = C13.parse_int_csv(cfg.density_nodes)
    budgets = C13.parse_int_csv(cfg.budgets)
    focal_ws = C13.parse_float_csv(cfg.focal_ws)
    rows: List[Dict[str, Any]] = []

    for suite_idx, suite in enumerate(C13.parse_csv(cfg.eval_suites)):
        if suite not in specs:
            raise KeyError(f"unknown suite {suite!r}; have {sorted(specs)}")
        accepted = 0
        candidate_worlds = int(cfg.eval_worlds) * int(cfg.max_world_retries)
        for _, world, world_seed in C13.iter_worlds(
            specs[suite],
            suite_idx,
            candidate_worlds,
            int(cfg.seed) + 900_000,
            retry=cfg.max_world_retries,
        ):
            roadmaps: Dict[int, Tuple[Optional[C.Roadmap], float]] = {}
            for density in densities:
                t_build = time.perf_counter()
                rm = C.build_prm(
                    world,
                    C.RoadmapConfig(n_nodes=int(density), k_neighbors=int(cfg.roadmap_k)),
                    seed=world_seed + 17,
                )
                roadmaps[int(density)] = (rm, time.perf_counter() - t_build)
            reference = roadmaps.get(int(cfg.train_nodes), (None, 0.0))[0]
            if reference is None:
                continue

            for density in densities:
                rm, build_seconds = roadmaps[int(density)]
                common = {
                    "suite": suite,
                    "world_index": accepted,
                    "world_seed": world_seed,
                    "roadmap_seed": world_seed + 17,
                    "requested_nodes": int(density),
                    "roadmap_k": int(cfg.roadmap_k),
                    "build_seconds": float(build_seconds),
                }
                if rm is None:
                    for budget in budgets:
                        rows.append(
                            {
                                **common,
                                "actual_nodes": 0,
                                "edges": 0,
                                "budget": int(budget),
                                "provider": "build_failure",
                                "mode": "none",
                                "focal_w": "",
                                "found": False,
                                "expansions": 0,
                                "closed": 0,
                                "cost": "",
                                "cost_ratio": "",
                                "inference_seconds": 0.0,
                                "search_seconds": 0.0,
                            }
                        )
                    continue

                euclid = C13.euclidean_to_goal(rm.points, rm.points[1])
                one_step = C13.one_step_euclidean_backup(rm.points, rm.adj)
                oracle = C13._finite_oracle(rm, world.side_len)
                optimal = float(rm.dist_to_goal[0])
                edges = sum(len(a) for a in rm.adj) // 2
                all_features = C13.make_local_state_features(world, rm.points, rm.adj, cfg.state_cfg())
                predictions: Dict[str, Tuple[np.ndarray, float]] = {}
                for model_name, model in models.items():
                    t_infer = time.perf_counter()
                    residual = C.predict_norm_residuals(model, all_features, device, batch_size=512)
                    inference_seconds = time.perf_counter() - t_infer
                    predictions[model_name] = (
                        euclid
                        + float(world.side_len)
                        * np.expm1(np.clip(residual, 0.0, float(cfg.max_norm_residual))),
                        inference_seconds,
                    )

                for budget in budgets:
                    base = {
                        **common,
                        "actual_nodes": len(rm.points),
                        "edges": edges,
                        "budget": int(budget),
                        "optimal_cost_eval_only": optimal,
                    }
                    rows.append(_run_astar(base, "euclid", rm.adj, euclid, budget, optimal))
                    rows.append(_run_astar(base, "one_step", rm.adj, one_step, budget, optimal))
                    rows.append(_run_astar(base, "oracle_eval_only", rm.adj, oracle, budget, optimal))
                    for focal_w in focal_ws:
                        rows.append(
                            _run_focal(
                                base,
                                "euclid_focal_rank",
                                rm.adj,
                                euclid,
                                euclid,
                                budget,
                                optimal,
                                focal_w,
                            )
                        )
                        rows.append(
                            _run_focal(
                                base,
                                "one_step_focal_rank",
                                rm.adj,
                                euclid,
                                one_step,
                                budget,
                                optimal,
                                focal_w,
                            )
                        )
                    for model_name, (rank, inference_seconds) in predictions.items():
                        rows.append(
                            _run_astar(
                                base,
                                f"{model_name}_td_additive_diagnostic",
                                rm.adj,
                                rank,
                                budget,
                                optimal,
                                inference_seconds=inference_seconds,
                            )
                        )
                        for focal_w in focal_ws:
                            t_search = time.perf_counter()
                            result = focal_astar_search(
                                rm.adj,
                                euclid,
                                rank,
                                int(budget),
                                w=float(focal_w),
                            )
                            rows.append(
                                _search_row(
                                    base,
                                    f"{model_name}_td_rank",
                                    "focal",
                                    result,
                                    optimal,
                                    time.perf_counter() - t_search,
                                    focal_w=float(focal_w),
                                    inference_seconds=inference_seconds,
                                )
                            )
            accepted += 1
            if accepted >= int(cfg.eval_worlds):
                break
        if accepted < int(cfg.eval_worlds):
            raise RuntimeError(f"evaluation/{suite} under-filled: {accepted}/{cfg.eval_worlds}")

    results_dir = C13.ensure_dir(Path(cfg.out_dir) / "results")
    raw_path = C13.write_csv(results_dir / "c13_td_evaluation_raw.csv", rows)
    summary_rows = summarize_evaluation(rows)
    summary_path = C13.write_csv(results_dir / "c13_td_evaluation_summary.csv", summary_rows)
    manifest_path = C13.write_json(
        Path(cfg.out_dir) / "evaluation_manifest.json",
        {
            "experiment": "C13-B",
            "config": asdict(cfg),
            "target_source": TARGET_SOURCE,
            "target_aggregation": TARGET_AGGREGATION,
            "target_transform": TARGET_TRANSFORM,
            "shortest_path_target": SHORTEST_PATH_TARGET,
            "oracle_policy_access": ORACLE_POLICY_ACCESS,
            "primary_integration": "euclidean_anchored_focal_rank",
            "same_search_controls": ["euclid_focal_rank", "one_step_focal_rank"],
            "additive_astar_role": "diagnostic_only_no_optimality_claim",
            "dijkstra_role": "roadmap_connectivity_filter_and_evaluation_only",
            "checkpoints": {name: str(path) for name, path in checkpoints.items()},
            "raw": str(raw_path),
            "summary": str(summary_path),
        },
    )
    return {"raw": raw_path, "summary": summary_path, "manifest": manifest_path}


