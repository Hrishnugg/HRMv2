def resolve_device(name: str) -> torch.device:
    if str(name).lower() == "auto":
        return torch.device("cuda" if torch.cuda.is_available() else "cpu")
    return torch.device(name)


def _load_dataset(path: Path) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    with np.load(path) as data:
        x = data["x"].astype(np.float32)
        y = data["y"].astype(np.float32)
        counts = data["rollout_count"].astype(np.float32)
    weights = np.clip(np.sqrt(np.maximum(1.0, counts)), 1.0, 4.0).astype(np.float32)
    weights /= max(C.EPS, float(np.mean(weights)))
    return x, y, weights


def _regression_metrics(model: torch.nn.Module, x: np.ndarray, y: np.ndarray, device: torch.device) -> Dict[str, float]:
    prediction = C.predict_norm_residuals(model, x, device, batch_size=512)
    error = prediction - y.astype(np.float64)
    corr = float("nan")
    if len(y) > 2 and np.std(prediction) > 1.0e-8 and np.std(y) > 1.0e-8:
        corr = float(np.corrcoef(prediction, y)[0, 1])
    return {
        "mae": float(np.mean(np.abs(error))),
        "rmse": float(np.sqrt(np.mean(error * error))),
        "corr": corr,
        "prediction_mean": float(np.mean(prediction)),
        "target_mean": float(np.mean(y)),
    }


def train_ranker(
    cfg: C13TDConfig,
    model_name: str,
    train_path: Path,
    val_path: Path,
    device: torch.device,
) -> Path:
    configs = model_configs(cfg)
    if model_name not in configs:
        raise KeyError(f"unknown model {model_name!r}; have {sorted(configs)}")
    backbone_cfg = configs[model_name]
    x_train, y_train, weights = _load_dataset(train_path)
    x_val, y_val, _ = _load_dataset(val_path)
    C.set_global_seed(int(cfg.seed) + (17 if model_name == "hrm" else 29))
    model = C.ContinuousHeuristicModel(
        backbone_cfg,
        token_dim=int(cfg.state_cfg().token_dim),
        max_norm_residual=float(cfg.max_norm_residual),
    ).to(device)
    ds = TensorDataset(
        torch.from_numpy(x_train),
        torch.from_numpy(y_train),
        torch.from_numpy(weights),
    )
    loader = DataLoader(ds, batch_size=int(cfg.batch_size), shuffle=True, num_workers=0)
    optimizer = torch.optim.AdamW(model.parameters(), lr=float(cfg.lr), weight_decay=float(cfg.weight_decay))
    C.set_global_seed(int(cfg.seed) + (17 if model_name == "hrm" else 29))
    history: List[Dict[str, Any]] = []

    for epoch in range(1, int(cfg.epochs) + 1):
        model.train()
        losses: List[float] = []
        t0 = time.perf_counter()
        for xb, yb, wb in loader:
            xb = xb.to(device)
            yb = yb.to(device)
            wb = wb.to(device)
            optimizer.zero_grad(set_to_none=True)
            pred = model(xb)
            per_sample = F.smooth_l1_loss(pred, yb, reduction="none")
            loss = torch.sum(per_sample * wb) / torch.clamp(torch.sum(wb), min=C.EPS)
            if not torch.isfinite(loss):
                raise RuntimeError(f"nonfinite C13-B loss for {model_name}")
            loss.backward()
            if float(cfg.grad_clip) > 0.0:
                torch.nn.utils.clip_grad_norm_(model.parameters(), float(cfg.grad_clip))
            optimizer.step()
            losses.append(float(loss.item()))
        val_metrics = _regression_metrics(model, x_val, y_val, device)
        row = {
            "epoch": epoch,
            "train_loss": float(np.mean(losses)),
            "seconds": time.perf_counter() - t0,
            **{f"val_{key}": value for key, value in val_metrics.items()},
        }
        history.append(row)
        print(
            f"C13-B {model_name} epoch {epoch}/{cfg.epochs}: "
            f"loss={row['train_loss']:.5f} val_mae={row['val_mae']:.5f}",
            flush=True,
        )

    checkpoint_dir = C13.ensure_dir(Path(cfg.out_dir) / "checkpoints")
    checkpoint = checkpoint_dir / f"c13_td_{model_name}.pt"
    payload = {
        "model": model.state_dict(),
        "experiment": "C13-B",
        "model_name": model_name,
        "backbone_cfg": asdict(backbone_cfg),
        "state_cfg": asdict(cfg.state_cfg()),
        "target_source": TARGET_SOURCE,
        "target_aggregation": TARGET_AGGREGATION,
        "target_transform": TARGET_TRANSFORM,
        "shortest_path_target": SHORTEST_PATH_TARGET,
        "oracle_policy_access": ORACLE_POLICY_ACCESS,
        "max_log_residual": float(cfg.max_norm_residual),
        "history": history,
    }
    torch.save(payload, checkpoint)
    C13.write_json(
        Path(cfg.out_dir) / "logs" / f"train_c13_td_{model_name}.json",
        {key: value for key, value in payload.items() if key != "model"},
    )
    return checkpoint


def load_ranker(cfg: C13TDConfig, model_name: str, checkpoint: Path, device: torch.device) -> torch.nn.Module:
    payload = torch.load(checkpoint, map_location="cpu")
    if payload.get("shortest_path_target") is not False:
        raise ValueError(f"checkpoint {checkpoint} lacks the C13-B no-shortest-path provenance flag")
    if payload.get("target_transform") != TARGET_TRANSFORM:
        raise ValueError(f"checkpoint {checkpoint} has an incompatible target transform")
    backbone = C.BackboneConfig(**payload["backbone_cfg"])
    model = C.ContinuousHeuristicModel(
        backbone,
        token_dim=int(payload["state_cfg"]["token_dim"]),
        max_norm_residual=float(payload["max_log_residual"]),
    )
    model.load_state_dict(payload["model"], strict=True)
    model.to(device).eval()
    return model


